import { BaseRpcContext } from '@nestjs/microservices';
import { JsMsg, Msg, Match, MsgHdrs } from 'nats';
import { TRACE_ID_HEADER, REQUEST_ID_HEADER } from '../constants';
import { RequestContext } from '../context';

type NatsContextArgs = [JsMsg | Msg];

/**
 * @publicApi
 */
export class NatsContext extends BaseRpcContext<NatsContextArgs> {
  constructor(args: NatsContextArgs) {
    super(args);
  }

  /**
   * Returns the native NATS message object.
   */
  getMessage(): JsMsg | Msg {
    return this.args[0];
  }

  /**
   * Returns the name of the subject.
   */
  getSubject() {
    return this.args[0].subject;
  }

  /**
   * Returns message headers (if exist).
   */
  getHeaders(): MsgHdrs | undefined {
    return this.args[0].headers;
  }

  /**
   * Returns the effective trace ID for the current message processing:
   * from RequestContext (restored or generated by ServerNats with `requestContext: true`),
   * otherwise from the message header, or `undefined` if neither is available.
   */
  getTraceId(): string | undefined {
    return RequestContext.getTraceId() || this.args[0].headers?.get(TRACE_ID_HEADER, Match.IgnoreCase) || undefined;
  }

  /**
   * Returns the effective request ID for the current message processing:
   * from RequestContext (restored by ServerNats with `requestContext: true`),
   * otherwise from the message header, or `undefined` if neither is available.
   */
  getRequestId(): string | undefined {
    return RequestContext.getRequestId() || this.args[0].headers?.get(REQUEST_ID_HEADER, Match.IgnoreCase) || undefined;
  }
}
